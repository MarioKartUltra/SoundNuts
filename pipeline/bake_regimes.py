"""Bake pipeline/out/*.json regime maps into a C++ header so the plugin needs no
runtime file I/O or JSON parser. Emits dsp/include/soundnuts/registry_data.hpp.

Run:  python3 pipeline/bake_regimes.py
"""
import json, os, glob

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "out")
DST = os.path.join(HERE, "..", "dsp", "include", "soundnuts", "registry_data.hpp")
KMAXDIM = 8

REGIME = {
    "fixed_point": "Regime::FixedPoint",
    "limit_cycle": "Regime::LimitCycle",
    "chaos":       "Regime::Chaos",
    "divergent":   "Regime::Divergent",
}

def pad(vec, fill):
    v = list(vec) + [fill] * KMAXDIM
    return v[:KMAXDIM]

def fmt_arr(vec):
    return "{" + ", ".join(repr(float(x)) for x in vec) + "}"

def emit_system(d):
    lines = []
    for p in d["points"]:
        c = pad(p["center"], 0.0)
        s = pad(p["scale"], 0.0)
        reg = REGIME[p["regime"]]
        lines.append(
            "        RegimePoint{{ {b!r}, {reg}, {ly!r}, {per!r}, {c}, {s} }},".format(
                b=float(p["bifurcation"]), reg=reg,
                ly=float(p["largest_lyapunov"]), per=float(p["period"]),
                c=fmt_arr(c), s=fmt_arr(s)))
    return "\n".join(lines)

def main():
    systems = {}
    for f in sorted(glob.glob(os.path.join(OUT_DIR, "*.json"))):
        d = json.load(open(f))
        systems[d["id"]] = d

    out = []
    out.append("// SoundNuts — registry_data.hpp  (GENERATED by pipeline/bake_regimes.py)")
    out.append("// Baked offline regime maps (center/scale/regime per bifurcation point).")
    out.append("// Do not edit by hand; re-run the baker to regenerate.")
    out.append("#pragma once")
    out.append('#include "attractor_system.hpp"')
    out.append("")
    out.append("namespace soundnuts {")
    out.append("")
    out.append("// Populate `m` with the baked sweep for system `id` (no-op if unknown).")
    out.append("inline void fillRegimeMap(const std::string& id, RegimeMap& m) {")
    out.append("    m.points.clear();")
    first = True
    for sid, d in systems.items():
        kw = "if" if first else "else if"
        first = False
        out.append(f'    {kw} (id == "{sid}") {{')
        out.append("        m.points = {")
        out.append(emit_system(d))
        out.append("        };")
        out.append("    }")
    out.append("}")
    out.append("")
    out.append("}  // namespace soundnuts")
    out.append("")

    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(os.path.abspath(DST), "w") as fh:
        fh.write("\n".join(out))
    print(f"wrote {os.path.abspath(DST)} with systems: {', '.join(systems)}")

if __name__ == "__main__":
    main()
